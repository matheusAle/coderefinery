// profileHook is the React DevTools-hook profiler, embedded as text and
// written under .metrics/react-profile/ with a per-runner header.
//
//go:embed profile_hook.js
var profileHook string

// ProfileDir is .metrics/react-profile[/<slug>] for a package: slug is the
// package dir relative to root with / -> __, omitted at the root.
func ProfileDir(root, pkg string) string {
	base := filepath.Join(root, ".metrics", "react-profile")
	rel, ok := discover.RelativeTo(discover.Resolve(pkg), discover.Resolve(root))
	if !ok || rel == "." || rel == "" {
		return base
	}
	return filepath.Join(base, strings.ReplaceAll(rel, "/", "__"))
}

func jsString(s string) string {
	b, _ := json.Marshal(s)
	return string(b)
}

type packageJSON struct {
	Scripts map[string]string `json:"scripts"`
	Jest    json.RawMessage   `json:"jest"`
}

var (
	vitestConfigNames = []string{"vitest.config.ts", "vitest.config.mts", "vitest.config.cts", "vitest.config.js",
		"vitest.config.mjs", "vitest.config.cjs"}
	viteConfigNames = []string{"vite.config.ts", "vite.config.mts", "vite.config.cts", "vite.config.js",
		"vite.config.mjs", "vite.config.cjs"}
	jestConfigNames = []string{"jest.config.js", "jest.config.ts", "jest.config.mjs", "jest.config.cjs",
		"jest.config.cts", "jest.config.json"}
)

func firstFile(dir string, names []string) string {
	for _, n := range names {
		if p := filepath.Join(dir, n); discover.IsFile(p) {
			return p
		}
	}
	return ""
}

// ProfileRunner picks the package's test runner: Vitest first (the test
// script or a vitest.config.*), then Jest (the test script, a jest.config.*
// or a "jest" key in package.json). "" when neither is used.
func ProfileRunner(pkg string) string {
	var data packageJSON
	if raw, err := os.ReadFile(filepath.Join(pkg, "package.json")); err == nil {
		_ = json.Unmarshal(raw, &data)
	}
	script := data.Scripts["test"]
	switch {
	case strings.Contains(script, "vitest") || firstFile(pkg, vitestConfigNames) != "":
		return "vitest"
	case strings.Contains(script, "jest") || firstFile(pkg, jestConfigNames) != "" || len(data.Jest) > 0:
		return "jest"
	}
	return ""
}

// scriptConfig is the --config/-c value in the test script, "" without.
func scriptConfig(script string) string {
	fields := strings.Fields(script)
	for i, f := range fields {
		if v, ok := strings.CutPrefix(f, "--config="); ok {
			return v
		}
		if (f == "--config" || f == "-c") && i+1 < len(fields) {
			return fields[i+1]
		}
	}
	return ""
}

// VitestUserConfig is the config Vitest would load in pkg: --config in the
// test script, else vitest.config.*, else vite.config.* ("" = none).
func VitestUserConfig(pkg string) string {
	var data packageJSON
	if raw, err := os.ReadFile(filepath.Join(pkg, "package.json")); err == nil {
		_ = json.Unmarshal(raw, &data)
	}
	if c := scriptConfig(data.Scripts["test"]); c != "" {
		return filepath.Join(pkg, c)
	}
	if c := firstFile(pkg, vitestConfigNames); c != "" {
		return c
	}
	return firstFile(pkg, viteConfigNames)
}

// VitestSetup is the generated Vitest setup file: the hook, flushed after
// each test file.
func VitestSetup(out string) string {
	return "// Generated by coderefinery react --profile. Safe to delete.\n" +
		"import { writeFileSync } from \"node:fs\";\nimport { afterAll } from \"vitest\";\n" +
		"var OUT = " + jsString(out) + ";\nfunction writeFile(path, text) { writeFileSync(path, text); }\n" +
		profileHook + "\nafterAll(__coderefineryFlush);\n"
}

// VitestConfig extends the user's config (any form: object, promise or
// function) with the setup file first in test.setupFiles, so the hook is
// in place before any user setup file loads react-dom.
func VitestConfig(userConfig, setup string) string {
	var b strings.Builder
	b.WriteString("// Generated by coderefinery react --profile. Safe to delete.\n")
	if userConfig != "" {
		b.WriteString("// Extends " + userConfig + "\nimport base from " + jsString(userConfig) + ";\n")
	} else {
		b.WriteString("const base = {};\n")
	}
	b.WriteString("const SETUP = " + jsString(setup) + `;
function extend(config) {
  config = config || {};
  const test = config.test || {};
  const files = test.setupFiles == null ? [] : [].concat(test.setupFiles);
  return { ...config, test: { ...test, setupFiles: [SETUP, ...files] } };
}
export default typeof base === "function" ? async (env) => extend(await base(env)) : Promise.resolve(base).then(extend);
`)
	return b.String()
}

// JestSetup is the generated Jest setupFiles entry (runs before the test
// framework): the hook, with the flush exposed for JestSetupAfterEnv.
func JestSetup(out string) string {
	return "// Generated by coderefinery react --profile. Safe to delete.\n" +
		"var fs = require(\"fs\");\nvar OUT = " + jsString(out) + ";\n" +
		"function writeFile(path, text) { fs.writeFileSync(path, text); }\n" +
		profileHook + "\nglobalThis.__coderefineryFlush = __coderefineryFlush;\n"
}

// JestSetupAfterEnv flushes after each test file.
const JestSetupAfterEnv = "// Generated by coderefinery react --profile. Safe to delete.\n" +
	"afterAll(function () { if (globalThis.__coderefineryFlush) globalThis.__coderefineryFlush(); });\n"

// nodeBin finds node_modules/.bin/<name> from pkg up to root; npx without.
func nodeBin(pkg, root, name string) []string {
	stop := discover.Resolve(root)
	for cur := discover.Resolve(pkg); ; cur = filepath.Dir(cur) {
		if bin := filepath.Join(cur, "node_modules", ".bin", name); discover.IsFile(bin) {
			return []string{bin}
		}
		if cur == stop || filepath.Dir(cur) == cur {
			return []string{"npx", "--no-install", name}
		}
	}
}

// jestShowConfig is the part of `jest --showConfig` the profile needs.
type jestShowConfig struct {
	Configs []struct {
		SetupFiles         []string `json:"setupFiles"`
		SetupFilesAfterEnv []string `json:"setupFilesAfterEnv"`
	} `json:"configs"`
}

// JestArgs prepends the hook to the user's resolved setupFiles and appends
// the flush to setupFilesAfterEnv: Jest's CLI flags replace the config's
// lists, so the user's entries are passed back explicitly.
func JestArgs(showConfig []byte, setup, afterEnv string) ([]string, error) {
	var sc jestShowConfig
	if err := json.Unmarshal(showConfig, &sc); err != nil {
		return nil, fmt.Errorf("--profile: cannot read jest --showConfig: %v", err)
	}
	if len(sc.Configs) != 1 {
		return nil, fmt.Errorf("--profile: Jest projects (%d configs) are not supported", len(sc.Configs))
	}
	args := []string{"--ci", "--coverage=false", "--setupFiles", setup}
	for _, f := range sc.Configs[0].SetupFiles {
		args = append(args, "--setupFiles", f)
	}
	for _, f := range sc.Configs[0].SetupFilesAfterEnv {
		args = append(args, "--setupFilesAfterEnv", f)
	}
	return append(args, "--setupFilesAfterEnv", afterEnv), nil
}

func writeGenerated(files map[string]string) error {
	for path, text := range files {
		if err := os.MkdirAll(filepath.Dir(path), 0o777); err != nil {
			return err
		}
		if err := os.WriteFile(path, []byte(text), 0o666); err != nil {
			return err
		}
	}
	return nil
}

// profileCommand writes the generated files for pkg into out and returns
// the test command.
func profileCommand(runner, pkg, root, out string) ([]string, error) {
	switch runner {
	case "vitest":
		setup, config := filepath.Join(out, "setup.vitest.mjs"), filepath.Join(out, "vitest.config.mjs")
		if err := writeGenerated(map[string]string{setup: VitestSetup(out),
			config: VitestConfig(VitestUserConfig(pkg), setup)}); err != nil {
			return nil, err
		}
		return append(nodeBin(pkg, root, "vitest"), "run", "--config", config, "--root", pkg,
			"--coverage.enabled=false"), nil
	case "jest":
		setup, afterEnv := filepath.Join(out, "setup.jest.cjs"), filepath.Join(out, "setup-after-env.jest.cjs")
		if err := writeGenerated(map[string]string{setup: JestSetup(out), afterEnv: JestSetupAfterEnv}); err != nil {
			return nil, err
		}
		jest := nodeBin(pkg, root, "jest")
		show := exec.Command(jest[0], append(jest[1:], "--showConfig")...)
		show.Dir = pkg
		var stdout, stderr bytes.Buffer
		show.Stdout, show.Stderr = &stdout, &stderr
		if err := show.Run(); err != nil {
			return nil, fmt.Errorf("--profile: jest --showConfig failed in %s: %s", pkg,
				strings.SplitN(strings.TrimSpace(stderr.String()+" "+err.Error()), "\n", 2)[0])
		}
		args, err := JestArgs(stdout.Bytes(), setup, afterEnv)
		if err != nil {
			return nil, err
		}
		return append(jest, args...), nil
	}
	return nil, fmt.Errorf("--profile: no Vitest or Jest test setup in %s", pkg)
}

// RunProfile runs each package's tests with the render profiler and merges
// the results. failed reports a test run that exited non-zero; err is a
// one-line reason the run could not be instrumented or measured. The test
// output goes to stderr: stdout is the report.
func RunProfile(root string, files []string, stderr io.Writer) (p Profile, failed bool, err error) {
	packages := coverage.TypescriptPackages(root, files)
	if len(packages) == 0 {
		return p, false, fmt.Errorf("--profile: no package.json above the analyzed files")
	}
	runner := &coverage.Runner{Stdout: stderr, Stderr: stderr}
	for _, pkg := range packages {
		name := ProfileRunner(pkg)
		out := ProfileDir(root, pkg)
		old, _ := filepath.Glob(filepath.Join(out, "profile-*.json"))
		for _, f := range old {
			_ = os.Remove(f)
		}
		cmd, err := profileCommand(name, pkg, root, out)
		if err != nil {
			return p, false, err
		}
		p.Runners = append(p.Runners, name)
		if runner.RunShell(coverage.Argv(cmd...), pkg) != 0 {
			return p, true, nil
		}
		if err := p.ReadProfiles(out); err != nil {
			return p, false, err
		}
	}
	if problem := p.Problem(); problem != "" {
		return p, false, fmt.Errorf("%s", problem)
	}
	return p, false, nil
}
